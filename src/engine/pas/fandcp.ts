// PAS: FANDCP.PAS UniToUtf8 – code point -> UTF-8 byte string
export function UniToUtf8(U: number): string {
  if (U < 0x80) return String.fromCharCode(U);
  if (U < 0x800) return String.fromCharCode(0xc0 | (U >>> 6), 0x80 | (U & 0x3f));
  if (U < 0x10000) {
    return String.fromCharCode(0xe0 | (U >>> 12), 0x80 | ((U >>> 6) & 0x3f), 0x80 | (U & 0x3f));
  }
  return String.fromCharCode(
    0xf0 | (U >>> 18), 0x80 | ((U >>> 12) & 0x3f), 0x80 | ((U >>> 6) & 0x3f), 0x80 | (U & 0x3f),
  );
}
// PAS: FANDCP.PAS AsciiFallback (private) – '' when there is none
function AsciiFallback(U: number): string {
  switch (U) {
    case 0x00a0: case 0x2002: case 0x2003: case 0x2009: case 0x202f:
      return ' ';
    case 0x2010: case 0x2011: case 0x2012: case 0x2013: case 0x2014: case 0x2015: case 0x2212:
      return '-';
    case 0x2018: case 0x2019: case 0x201a: case 0x201b: case 0x2032:
      return "'";
    case 0x201c: case 0x201d: case 0x201e: case 0x201f: case 0x2033: case 0x00ab: case 0x00bb:
      return '"';
    case 0x2026:
      return '...';
    case 0x2022: case 0x00b7:
      return '*';
    case 0x20ac:
      return 'EUR';
    case 0x2122:
      return '(TM)';
    case 0x00a9:
      return '(C)';
    case 0x00ae:
      return '(R)';
    default:
      return '';
  }
}
// PAS: FANDCP.PAS NextUtf8 – decodes the sequence at 1-based I and advances I
export function NextUtf8(S: string, I: Ref<number>): number {
  const c = S.charCodeAt(I.v - 1);
  I.v++;
  if (c < 0x80) return c;
  let u: number;
  let n: number;
  if ((c & 0xe0) === 0xc0) {
    u = c & 0x1f;
    n = 1;
  } else if ((c & 0xf0) === 0xe0) {
    u = c & 0x0f;
    n = 2;
  } else if ((c & 0xf8) === 0xf0) {
    u = c & 0x07;
    n = 3;
  } else return c;
  for (let k = 1; k <= n; k++) {
    if (I.v > S.length || (S.charCodeAt(I.v - 1) & 0xc0) !== 0x80) return 0xfffd;
    u = (u << 6) | (S.charCodeAt(I.v - 1) & 0x3f);
    I.v++;
  }
  return u;
}
// PAS: FANDCP.PAS S852ToUtf8
export function S852ToUtf8(S: string): string {
  let r = '';
  for (let i = 0; i < S.length; i++) {
    const c = S.charCodeAt(i);
    if (c < 0x80) r += S[i];
    else r += UniToUtf8(Cp852Uni[c - 0x80]);
  }
  return r;
}
// PAS: FANDCP.PAS S1250ToUtf8
export function S1250ToUtf8(S: string): string {
  let r = '';
  for (let i = 0; i < S.length; i++) {
    const c = S.charCodeAt(i);
    if (c < 0x80) r += S[i];
    else {
      const u = Cp1250Uni[c - 0x80];
      if (u === 0) r += '?';
      else r += UniToUtf8(u);
    }
  }
  return r;
}
// PAS: FANDCP.PAS FromUni (private)
function FromUni(U: number, Tab: Uint16Array, Hit: Ref<boolean>): string {
  Hit.v = true;
  if (U < 0x80) return String.fromCharCode(U);
  for (let k = 0; k <= 127; k++) if (Tab[k] === U) return String.fromCharCode(k + 0x80);
  Hit.v = false;
  return '?';
}
// PAS: FANDCP.PAS Utf8ToTab (private)
function Utf8ToTab(S: string, Tab: Uint16Array): string {
  let r = '';
  const i = { v: 1 };
  const hit = { v: false };
  while (i.v <= S.length) {
    const u = NextUtf8(S, i);
    const c = FromUni(u, Tab, hit);
    if (hit.v) r += c;
    else {
      const f = AsciiFallback(u);
      if (f === '') r += '?';
      else r += f;
    }
  }
  return r;
}
// PAS: FANDCP.PAS SUtf8To852
export function SUtf8To852(S: string): string {
  return Utf8ToTab(S, Cp852Uni);
}
// PAS: FANDCP.PAS SUtf8To1250
export function SUtf8To1250(S: string): string {
  return Utf8ToTab(S, Cp1250Uni);
}
// PAS: FANDCP.PAS S852To1250
export function S852To1250(S: string): string {
  let r = '';
  for (let i = 0; i < S.length; i++) {
    const c = S.charCodeAt(i);
    r += c >= 0x80 ? String.fromCharCode(Cp852To1250[c - 0x80]) : S[i];
  }
  return r;
}
// PAS: FANDCP.PAS S1250To852
export function S1250To852(S: string): string {
  return SUtf8To852(S1250ToUtf8(S));
}
